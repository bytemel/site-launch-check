// One pure function per check. Each takes facts already gathered and returns
// { status: "PASS" | "WARN" | "FAIL" | "SKIP", detail, items }. No network here, so each rule is easy to test.

const r = (status, detail, items = []) => ({ status, detail, items });
const kb = (bytes) => `${Math.round(bytes / 1024)} KB`;
export const isLocalHost = (host) => /^(localhost|127\.\d+\.\d+\.\d+|\[?::1\]?|\d+\.\d+\.\d+\.\d+)$/.test(host) || !host.includes(".");
export const bareHost = (host) => host.replace(/^www\./, "");

// 1. HTTPS and one canonical host
export function judgeHttps({ final, hops = [], httpProbe, altHost, altFinal, altError }) {
  const u = new URL(final);
  const fails = []; const warns = []; const good = [];
  if (u.protocol === "https:") good.push("served over HTTPS");
  else fails.push(`the site is served over plain HTTP (${u.origin})`);
  if (httpProbe) {
    const toHttps = httpProbe.status >= 300 && httpProbe.status < 400 && httpProbe.location?.startsWith("https://");
    if (toHttps && [301, 308].includes(httpProbe.status)) good.push(`http:// ${httpProbe.status}s to https://`);
    else if (toHttps) warns.push(`http:// redirects with ${httpProbe.status}; use a permanent 301 or 308`);
    else if (httpProbe.status === 200) fails.push("http:// serves the page instead of redirecting to https://");
    else if (httpProbe.status) warns.push(`http:// answers ${httpProbe.status} without redirecting to https://`);
  }
  if (altHost === null) good.push("www check skipped for a local host");
  else if (altError) warns.push(`${altHost} does not load (${altError}); people who type it get an error`);
  else if (altFinal && new URL(altFinal).host !== u.host) fails.push(`${altHost} ends at ${new URL(altFinal).host}, not ${u.host}: two hosts serve the site`);
  else if (altFinal) good.push(`${altHost} redirects to ${u.host}`);
  if (hops.length > 2) warns.push(`${hops.length} redirects before the home page loads; aim for one`);
  const notes = [...fails, ...warns];
  if (fails.length) return r("FAIL", fails[0], notes);
  if (warns.length) return r("WARN", warns[0], notes);
  return r("PASS", good.join(", "));
}

// 2. Home page returns 200
export function judgeStatus({ status, error, type = "" }) {
  if (!status) return r("FAIL", `the page did not load (${error || "no response"})`);
  if (status !== 200) return r("FAIL", `the home page answers HTTP ${status}, not 200`);
  if (type && !/html/i.test(type)) return r("WARN", `200, but the content type is ${type}`);
  return r("PASS", "200 OK");
}

// 3. Title
const DEFAULT_TITLE = /^(create next app|react app|vite \+ react|vite app|home|document|untitled|my app|next\.js|new project|index)$/i;
export function judgeTitle(title) {
  if (!title) return r("FAIL", "no <title>");
  if (DEFAULT_TITLE.test(title)) return r("FAIL", `default title "${title}"`);
  if (title.length > 60) return r("WARN", `${title.length} chars, keep it under 60 so it is not cut off in search results`, [title]);
  if (title.length < 10) return r("WARN", `${title.length} chars, too short to say what the page is`, [title]);
  return r("PASS", `${title.length} chars: "${title}"`);
}

// 4. Meta description
export function judgeDescription(desc) {
  if (desc === null || desc === "") return r("FAIL", "no meta description");
  if (/generated by create next app|^description$|lorem ipsum/i.test(desc)) return r("FAIL", `default description "${desc.slice(0, 50)}"`);
  if (desc.length < 110 || desc.length > 160) return r("WARN", `${desc.length} chars, aim for 110 to 160`, [desc]);
  return r("PASS", `${desc.length} chars`);
}

// 5. Canonical tag
export function judgeCanonical({ href, pageUrl, status }) {
  if (!href) return r("WARN", 'no <link rel="canonical">');
  let abs;
  try { abs = new URL(href, pageUrl); } catch { return r("FAIL", `canonical "${href}" is not a valid URL`); }
  if (new URL(pageUrl).host !== abs.host) return r("FAIL", `canonical points to another host: ${abs.href}`);
  if (status && status !== 200) return r("FAIL", `canonical URL answers HTTP ${status}: ${abs.href}`);
  if (!/^https?:\/\//i.test(href)) return r("WARN", `canonical is relative ("${href}"); use the full URL`);
  return r("PASS", abs.href);
}

// 6. Open Graph and Twitter image
export function judgeSocial({ ogImage, ogStatus, ogType = "", twitterCard, twitterImage, twStatus }) {
  const items = [];
  if (!ogImage) return r("FAIL", "no og:image, so shared links show no picture", ["add <meta property=\"og:image\" content=\"https://.../og.png\"> (1200 x 630)"]);
  let status = "PASS";
  if (!/^https?:\/\//i.test(ogImage)) { status = "WARN"; items.push(`og:image is relative ("${ogImage}"); most crawlers need a full URL`); }
  if (ogStatus !== 200) return r("FAIL", `og:image does not load (${ogStatus || "no response"})`, [ogImage]);
  if (ogType && !/^image\//i.test(ogType)) { status = "WARN"; items.push(`og:image is served as ${ogType}, not an image`); }
  if (!twitterCard) { status = "WARN"; items.push('no twitter:card; add <meta name="twitter:card" content="summary_large_image">'); }
  if (twitterImage && twStatus !== 200) return r("FAIL", `twitter:image does not load (${twStatus || "no response"})`, [twitterImage]);
  const detail = status === "PASS" ? `og:image loads${twitterImage ? ", twitter:image loads" : ", X falls back to og:image"}` : items[0];
  return r(status, detail, items);
}

// 7. Favicon and apple-touch-icon
export function judgeIcons({ icons, fallback }) {
  if (!icons.length) {
    if (fallback?.status === 200) return r("WARN", "only /favicon.ico; add <link rel=\"icon\"> and an apple-touch-icon");
    return r("FAIL", "no favicon at all");
  }
  const bad = icons.filter((i) => i.status !== 200).map((i) => `${i.status || "no response"} ${i.href}`);
  if (bad.length) return r("FAIL", "an icon link returns an error", bad);
  if (!icons.some((i) => /apple-touch-icon/i.test(i.rel))) return r("WARN", `${icons.length} icon link(s), no apple-touch-icon for iPhone home screens`);
  return r("PASS", `${icons.length} icon links incl. apple-touch-icon`);
}

// 8. robots.txt
export function parseRobots(text) {
  const groups = [];
  let current = null;
  let lastWasAgent = false;
  const sitemaps = [];
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.replace(/#.*/, "").trim();
    const m = line.match(/^([a-z-]+)\s*:\s*(.*)$/i);
    if (!m) continue;
    const key = m[1].toLowerCase(); const value = m[2].trim();
    if (key === "sitemap") { sitemaps.push(value); continue; }
    if (key === "user-agent") {
      if (!lastWasAgent) { current = { agents: [], rules: [] }; groups.push(current); }
      current.agents.push(value.toLowerCase());
      lastWasAgent = true;
      continue;
    }
    lastWasAgent = false;
    if (current && (key === "disallow" || key === "allow")) current.rules.push({ key, value });
  }
  const star = groups.filter((g) => g.agents.includes("*"));
  const blocksAll = star.some((g) => g.rules.some((x) => x.key === "disallow" && x.value === "/") && !g.rules.some((x) => x.key === "allow" && x.value === "/"));
  return { sitemaps, blocksAll };
}

export function judgeRobots({ status, type = "", text = "" }) {
  if (status !== 200) return r("WARN", `/robots.txt answers ${status || "no response"}; add one that points to your sitemap`);
  if (/html/i.test(type) || /^\s*<(!doctype|html)/i.test(text)) return r("FAIL", "/robots.txt returns an HTML page, not a robots file");
  const robots = parseRobots(text);
  if (robots.blocksAll) return r("FAIL", "robots.txt blocks every crawler (User-agent: * / Disallow: /)");
  if (!robots.sitemaps.length) return r("WARN", "robots.txt has no Sitemap: line");
  return r("PASS", `present, allows crawling, points to ${robots.sitemaps.join(", ")}`);
}

// 9. sitemap.xml
export const sitemapLocs = (xml) => [...String(xml).matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/gi)].map((m) => m[1].replace(/&amp;/g, "&"));
export function judgeSitemap({ url, status, text = "", pageUrl, robotsSitemaps = [] }) {
  if (status !== 200) return r("FAIL", `no sitemap at ${url} (${status || "no response"})`);
  if (!/<(urlset|sitemapindex)[\s>]/i.test(text)) return r("FAIL", `${url} is not a sitemap (no <urlset> or <sitemapindex>)`);
  const locs = sitemapLocs(text);
  if (!locs.length) return r("FAIL", "the sitemap lists no URLs");
  const origin = new URL(pageUrl).origin;
  const off = locs.filter((l) => { try { return new URL(l).origin !== origin; } catch { return true; } });
  const items = off.slice(0, 5).map((l) => `listed on another host or scheme: ${l}`);
  for (const s of robotsSitemaps) { try { if (new URL(s).origin !== origin) items.push(`robots.txt Sitemap: line uses ${new URL(s).origin}, the site is ${origin}`); } catch { items.push(`robots.txt Sitemap: "${s}" is not a full URL`); } }
  if (off.length) return r("FAIL", `${off.length} of ${locs.length} sitemap URLs are not on ${origin}`, items);
  if (items.length) return r("WARN", items[0], items);
  return r("PASS", `${locs.length} URL(s), all on ${origin}`);
}

// 10. noindex left on by mistake
export function judgeNoindex({ metaRobots = [], header = "" }) {
  const hits = [...metaRobots.filter((c) => /noindex|\bnone\b/i.test(c)).map((c) => `<meta name="robots" content="${c}">`)];
  if (/noindex|\bnone\b/i.test(header || "")) hits.push(`X-Robots-Tag: ${header}`);
  return hits.length ? r("FAIL", "the home page tells search engines not to index it", hits) : r("PASS", "no noindex in meta tags or headers");
}

// 11. Viewport meta
export function judgeViewport(content) {
  if (!content) return r("FAIL", 'no <meta name="viewport">; phones will show a zoomed out desktop page');
  if (!/width\s*=\s*device-width/i.test(content)) return r("FAIL", `viewport "${content}" is missing width=device-width`);
  if (/user-scalable\s*=\s*(no|0)|maximum-scale\s*=\s*1(\.0)?\b/i.test(content)) return r("WARN", "viewport blocks pinch zoom, which hurts people with low vision", [content]);
  return r("PASS", content);
}

// 12. lang attribute
export function judgeLang(lang) {
  if (lang === null || !lang.trim()) return r("FAIL", "<html> has no lang attribute; screen readers guess the language");
  if (!/^[a-z]{2,3}(-[a-z0-9]{2,8})*$/i.test(lang.trim())) return r("WARN", `lang="${lang}" does not look like a language code`);
  return r("PASS", `lang="${lang}"`);
}

// 13. A missing page returns 404
export function judge404({ status, hops = [], homeLink = false, error }) {
  if (!status) return r("WARN", `could not load a made up URL (${error || "no response"})`);
  if (hops.length && status === 200) return r("FAIL", `a missing page redirects to ${hops[hops.length - 1].location} and answers 200; search engines see a soft 404`);
  if (status === 200) return r("FAIL", "a missing page answers 200 (a soft 404); it should answer 404");
  if (status !== 404 && status !== 410) return r("WARN", `a missing page answers ${status}, expected 404`);
  if (!homeLink) return r("WARN", "404 status is right, but the page has no link back to the home page");
  return r("PASS", "a missing page answers 404 and links home");
}

// 14. Mixed content
const ACTIVE = { script: "src", iframe: "src", embed: "src", object: "data" };
const PASSIVE = { img: "src", audio: "src", video: "src", source: "src", track: "src" };
export function judgeMixed(pageUrl, tags) {
  if (new URL(pageUrl).protocol !== "https:") return r("SKIP", "not checked: the page itself is not HTTPS (see check 1)");
  const active = []; const passive = [];
  const insecure = (v) => /^\s*http:\/\//i.test(v || "");
  for (const t of tags) {
    if (ACTIVE[t.name] && insecure(t.attrs[ACTIVE[t.name]])) active.push(`<${t.name}> ${t.attrs[ACTIVE[t.name]]}`);
    if (t.name === "link" && /stylesheet|preload|modulepreload/i.test(t.attrs.rel || "") && insecure(t.attrs.href)) active.push(`<link rel="${t.attrs.rel}"> ${t.attrs.href}`);
    if (t.name === "form" && insecure(t.attrs.action)) active.push(`<form action> ${t.attrs.action}`);
    if (PASSIVE[t.name] && insecure(t.attrs[PASSIVE[t.name]])) passive.push(`<${t.name}> ${t.attrs[PASSIVE[t.name]]}`);
    if ((t.name === "img" || t.name === "source") && /(^|,)\s*http:\/\//i.test(t.attrs.srcset || "")) passive.push(`<${t.name} srcset> ${t.attrs.srcset.slice(0, 80)}`);
  }
  if (active.length) return r("FAIL", `${active.length} script, style, frame or form URL(s) use http://; browsers block them`, [...active, ...passive]);
  if (passive.length) return r("WARN", `${passive.length} image or media URL(s) use http://`, passive);
  return r("PASS", "no http:// resources on the HTTPS page");
}

// 15. Heavy images
export function judgeImages(images) {
  if (!images.length) return r("PASS", "no images on the home page");
  const broken = images.filter((i) => i.status !== 200).map((i) => `${i.status || i.error || "no response"} ${i.url}`);
  const heavy = images.filter((i) => i.status === 200 && i.bytes > 500 * 1024).map((i) => `${kb(i.bytes)} ${i.url}`);
  const big = images.filter((i) => i.status === 200 && i.bytes > 200 * 1024 && i.bytes <= 500 * 1024).map((i) => `${kb(i.bytes)} ${i.url}`);
  if (broken.length || heavy.length) return r("FAIL", `${heavy.length} image(s) over 500 KB, ${broken.length} broken`, [...broken, ...heavy, ...big]);
  if (big.length) return r("WARN", `${big.length} image(s) over 200 KB`, big);
  const total = images.reduce((a, i) => a + i.bytes, 0);
  return r("PASS", `${images.length} image(s), ${kb(total)} total, none over 200 KB`);
}

// 16. Missing alt text
export function judgeAlt(tags) {
  const imgs = tags.filter((t) => t.name === "img" || (t.name === "input" && (t.attrs.type || "").toLowerCase() === "image"));
  const missing = imgs.filter((t) => !("alt" in t.attrs) && t.attrs["aria-hidden"] !== "true" && !/presentation|none/i.test(t.attrs.role || "") && !t.attrs["aria-label"] && !t.attrs["aria-labelledby"]);
  if (missing.length) return r("FAIL", `${missing.length} of ${imgs.length} image(s) have no alt attribute (use alt="" for decoration)`, missing.map((t) => t.attrs.src || t.attrs["data-src"] || "(no src)"));
  return r("PASS", imgs.length ? `all ${imgs.length} image(s) have alt text or alt=""` : "no images on the home page");
}

// 17. Broken internal links
export function judgeLinks(links, { checked, total }) {
  if (!total) return r("WARN", "no internal links found on the home page");
  const broken = links.filter((l) => (l.status === 0 && l.error !== "timeout") || l.status === 404 || l.status === 410 || l.status >= 500).map((l) => `${l.status || l.error} ${l.url}`);
  const blocked = links.filter((l) => [401, 403, 429].includes(l.status) || l.error === "timeout").map((l) => `${l.status || l.error} ${l.url}`);
  const scope = checked < total ? `first ${checked} of ${total}` : `${total}`;
  if (broken.length) return r("FAIL", `${broken.length} of ${scope} internal link(s) broken`, [...broken, ...blocked]);
  if (blocked.length) return r("WARN", `${blocked.length} link(s) refused or timed out; open them by hand`, blocked);
  return r("PASS", `${scope} internal link(s) all resolve`);
}

// 18. Security headers
export function judgeHeaders(get, isHttps) {
  const hsts = get("strict-transport-security") || "";
  const nosniff = /nosniff/i.test(get("x-content-type-options") || "");
  const xfo = /^(deny|sameorigin)$/i.test((get("x-frame-options") || "").trim());
  const fa = /frame-ancestors/i.test(get("content-security-policy") || "");
  const missing = [];
  if (!isHttps) missing.push("Strict-Transport-Security (needs HTTPS first)");
  else if (!/max-age\s*=\s*[1-9]/i.test(hsts)) missing.push("Strict-Transport-Security: max-age=63072000; includeSubDomains");
  if (!nosniff) missing.push("X-Content-Type-Options: nosniff");
  if (!xfo && !fa) missing.push("X-Frame-Options: DENY (or CSP frame-ancestors)");
  if (missing.length === 3) return r("FAIL", "none of HSTS, nosniff or frame protection is set", missing);
  if (missing.length) return r("WARN", `${missing.length} header(s) missing`, missing);
  return r("PASS", "HSTS, nosniff and frame protection set");
}

// 19. Structured data
export function judgeStructured(tags) {
  const blocks = tags.filter((t) => t.name === "script" && (t.attrs.type || "").toLowerCase() === "application/ld+json");
  const types = []; const bad = [];
  blocks.forEach((b, i) => {
    try {
      const data = JSON.parse(b.text || "");
      const nodes = Array.isArray(data) ? data : data["@graph"] ? data["@graph"] : [data];
      for (const n of nodes) if (n && n["@type"]) types.push([].concat(n["@type"]).join("/"));
    } catch (e) { bad.push(`JSON-LD block ${i + 1} is not valid JSON: ${e.message.slice(0, 80)}`); }
  });
  if (bad.length) return r("FAIL", `${bad.length} JSON-LD block(s) do not parse`, bad);
  if (!blocks.length) {
    if (tags.some((t) => "itemscope" in t.attrs)) return r("PASS", "microdata found (itemscope)");
    return r("WARN", "no JSON-LD; add Organization or WebSite data so search engines know who you are");
  }
  return r("PASS", `${blocks.length} JSON-LD block(s): ${types.join(", ") || "no @type"}`);
}

// 20. Page weight
export function judgePageWeight({ htmlBytes, resources }) {
  const total = htmlBytes + resources.reduce((a, x) => a + (x.bytes || 0), 0);
  const top = [...resources].sort((a, b) => b.bytes - a.bytes).slice(0, 5).map((x) => `${kb(x.bytes)} ${x.url}`);
  const detail = `${kb(total)} across the HTML and ${resources.length} file(s)`;
  if (total > 4 * 1024 * 1024) return r("FAIL", `${detail}; over 4 MB is slow on mobile data`, top);
  if (total > 2 * 1024 * 1024 || htmlBytes > 500 * 1024) return r("WARN", `${detail}; aim for under 2 MB${htmlBytes > 500 * 1024 ? ` (the HTML alone is ${kb(htmlBytes)})` : ""}`, top);
  return r("PASS", detail);
}
